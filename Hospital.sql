-- Calculate total revenue generated by each department.

SELECT

    dept.department_name,
    SUM(b.bill_amount) AS total_revenue

FROM billing b

JOIN patients p
ON b.patient_id = p.patient_id

JOIN departments dept
ON p.department_id = dept.department_id

GROUP BY dept.department_name

ORDER BY total_revenue DESC;



SELECT

    dept.department_name,
    ROUND(AVG(b.bill_amount),2) AS average_bill

FROM billing b

JOIN patients p
ON b.patient_id = p.patient_id

JOIN departments dept
ON p.department_id = dept.department_id

GROUP BY dept.department_name

ORDER BY average_bill DESC;


