ON p.patient_id = b.patient_id

LEFT JOIN prescriptions pr
ON p.patient_id = pr.patient_id

LEFT JOIN lab_tests l
ON p.patient_id = l.patient_id;


CREATE VIEW hospital_master_view AS

SELECT

    p.patient_id,
    p.name,
    p.gender,
    p.age,
    p.city,
    p.admission_date,
    p.discharge_date,
    p.status,
    p.diagnosis,

    d.doctor_name,
    d.gender AS doctor_gender,
    d.experience_years,

    dept.department_name,

    a.appointment_date,
    a.appointment_status,

    b.bill_amount,
    b.payment_method,

    pr.medicine_name,
    pr.days,

    l.test_name,
    l.result

FROM patients p

LEFT JOIN doctors d
ON p.doctor_id = d.doctor_id

LEFT JOIN departments dept
ON p.department_id = dept.department_id

LEFT JOIN appointments a
ON p.patient_id = a.patient_id

LEFT JOIN billing b
ON p.patient_id = b.patient_id

LEFT JOIN prescriptions pr
ON p.patient_id = pr.patient_id

LEFT JOIN lab_tests l
ON p.patient_id = l.patient_id;

